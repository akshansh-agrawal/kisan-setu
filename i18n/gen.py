import json,glob,os
keys=[k for k,_ in json.load(open('i18n/keys.json'))]
def line(f,i): 
    L=[l for l in open(f,encoding='utf8').read().split('\n') if l.strip()]
    return [x.strip() for x in L[i].split('¦')]
en=line('i18n/en_b.txt',0); assert len(en)==98
pack={}
for f in sorted(glob.glob('i18n/*.txt')):
    c=os.path.basename(f)[:-4]
    if c in('en_b',): continue
    if c in('hi','mr','pa'): pack[c]=[[],line(f,0)]
    else: pack[c]=[line(f,0),line(f,1)]
    assert len(pack[c][1]) in (95,97,98),(c,len(pack[c][1]))
    assert c in('hi','mr','pa') or len(pack[c][0])==106,c
out='/* generated by tr/gen.py: language packs (A = UI strings in DICT key order, B = Crop Doctor / guide strings) */\nconst EXT_A_KEYS = %s;\nconst EXT_EN_B = %s;\nconst EXT_PACK = %s;\n'%(json.dumps(keys),json.dumps(en,ensure_ascii=False),json.dumps(pack,ensure_ascii=False))
open('src/js/01c_i18n_ext.jsx','w',encoding='utf8').write(out)
print('packs:',sorted(pack))
